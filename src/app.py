"""Web interface: ask a question, show the answer with rendered formulas and its sources.

With API_URL set (Docker, compose), questions go to the HTTP API. Without it (Streamlit
Community Cloud), the engine runs inside this app and downloads the index at startup.
"""
import os

import requests
import streamlit as st

from citations import renumber

API_URL = os.getenv("API_URL")
EXAMPLES = [
    "What is a universal adversarial perturbation?",
    "Qu'est-ce qu'une attaque « data-free » ?",
    "Why does an adversarial example crafted on one model often fool another model?",
    "Comment peut-on protéger une image contre une modification par un modèle de diffusion ?",
]


class LLMUnavailable(Exception):
    """Every Gemini model is overloaded or out of quota."""


@st.cache_resource(show_spinner="Loading the model and the index (first visit only)...")
def load_engine():
    """In-process engine, created once per server and shared by all visitors."""
    from engine import Engine
    from fetch_index import download_index

    download_index()
    return Engine()


def ask_api(question):
    try:
        response = requests.post(f"{API_URL}/ask", json={"question": question}, timeout=120)
    except requests.RequestException:
        st.error(f"Cannot reach the API at {API_URL}. Is it running?")
        st.stop()
    if response.status_code == 503:
        raise LLMUnavailable
    if response.status_code != 200:
        st.error(f"Unexpected error (HTTP {response.status_code}).")
        st.stop()
    return response.json()


def ask_engine(question):
    try:
        return load_engine().ask(question)
    except RuntimeError as error:
        raise LLMUnavailable from error


st.set_page_config(page_title="adversarial-attacks-rag")
st.title("adversarial-attacks-rag")
st.caption(
    "Answers from 44 arXiv papers on adversarial attacks in computer vision, "
    "with the paper and page behind every claim."
)

if not API_URL:
    load_engine()  # load when the page opens so the first question does not wait

with st.form("ask"):
    question = st.text_area("Question, in English or French", max_chars=500)
    submitted = st.form_submit_button("Ask")

with st.expander("Example questions"):
    for example in EXAMPLES:
        st.markdown(f"- {example}")

if submitted:
    question = question.strip()
    if len(question) < 3:
        st.warning("Please type a question.")
        st.stop()

    with st.spinner("Searching the papers and writing the answer..."):
        try:
            result = ask_api(question) if API_URL else ask_engine(question)
        except LLMUnavailable:
            st.error("The language model is busy or out of quota. Please try again later.")
            st.stop()

    if not result["found"]:
        st.info("The answer is not in the 44 papers of the corpus.")
    else:
        answer, sources = renumber(result["answer"], result["sources"])
        st.markdown(answer)  # renders $...$ formulas
        st.subheader("Sources")
        for source in sources:
            paper = f"https://arxiv.org/abs/{source['arxiv_id']}"
            pdf_page = f"https://arxiv.org/pdf/{source['arxiv_id']}#page={source['page']}"
            st.markdown(
                f"**[{source['n']}]** [{source['title']}]({paper}), [page {source['page']}]({pdf_page})"
            )
    st.caption(f"Generated by {result['llm']}")